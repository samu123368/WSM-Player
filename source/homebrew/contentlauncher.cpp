	static bool IsElf( const u8 *data, u32 size )
	{
		return size >= 52 && data[ 0 ] == 0x7f && data[ 1 ] == 'E'
			&& data[ 2 ] == 'L' && data[ 3 ] == 'F' && data[ 4 ] == 1
			&& data[ 5 ] == 2 && data[ 18 ] == 0 && data[ 19 ] == 20;
	}

	static bool IsDol( const u8 *data, u32 size )
	{
		if( size < 0x101 )
			return false;

		const u32 *words = (const u32 *)data;
		bool hasSection = false;
		for( u32 i = 0; i < 18; ++i )
		{
			const u32 offset = words[ i ];
			const u32 sectionSize = words[ 0x90 / 4 + i ];
			if( sectionSize == 0 )
				continue;
			hasSection = true;
			if( offset > size || sectionSize > size - offset )
				return false;
		}

		const u32 entry = words[ 0xe0 / 4 ];
		return hasSection && entry >= 0x80000000 && entry < 0x94000000;
	}

	static bool IsDollZ( const u8 *data, u32 size )
	{
		return size > 0x100 && data[ 0x100 ] == 0x3c;
	}

	static bool IsSpecialElf( const u8 *data, u32 size )
	{
		return IsElf( data, size ) && size > 0x24 && data[ 0x24 ] == 0;
	}

	static FILE *OpenExecutable( const char *directory, std::string &path )
	{
		path = directory ? directory : "";
		while( !path.empty() && ( path[ path.size() - 1 ] == '/'
			|| path[ path.size() - 1 ] == '\\' ) )
			path.erase( path.size() - 1 );

		if( path.empty() )
			return NULL;

		const std::string base = path;
		path = base + "/boot.dol";
		FILE *file = fopen( path.c_str(), "rb" );
		if( file )
			return file;

		path = base + "/boot.elf";
		return fopen( path.c_str(), "rb" );
	}

	static s32 PrepareArguments( const std::string &executablePath,
		const std::vector< std::string > &extraArguments )
	{
		u32 total = 1;
		if( executablePath.size() + 1 >= MaxArgumentBytes )
			return ContentLauncher::ArgumentsTooLarge;
		total += executablePath.size() + 1;

		for( std::vector< std::string >::const_iterator it = extraArguments.begin();
			it != extraArguments.end(); ++it )
		{
			if( it->size() + 1 > MaxArgumentBytes - total )
				return ContentLauncher::ArgumentsTooLarge;
			total += it->size() + 1;
		}

		struct __argv *args = (struct __argv *)ArgumentsAddress;
		memset( args, 0, sizeof( *args ) + total );
		args->argvMagic = ARGV_MAGIC;
		args->commandLine = (char *)ArgumentsAddress + sizeof( *args );
		args->length = total;

		u32 position = 0;
		memcpy( args->commandLine + position, executablePath.c_str(),
			executablePath.size() + 1 );
		position += executablePath.size() + 1;
		++args->argc;

		for( std::vector< std::string >::const_iterator it = extraArguments.begin();
			it != extraArguments.end(); ++it )
		{
			memcpy( args->commandLine + position, it->c_str(), it->size() + 1 );
			position += it->size() + 1;
			++args->argc;
		}

		args->commandLine[ total - 1 ] = '\0';
		args->argv = &args->commandLine;
		args->endARGV = args->argv + 1;
		DCFlushRange( args, sizeof( *args ) + total );
		return 0;
	}

	static s32 LaunchHomebrew( const char *directory,
		const std::vector< std::string > &arguments )
	{
		if( !directory || !directory[ 0 ] )
			return ContentLauncher::InvalidArgument;

		std::string executablePath;
		FILE *file = OpenExecutable( directory, executablePath );
		if( !file )
			return ContentLauncher::ExecutableNotFound;

		if( fseek( file, 0, SEEK_END ) != 0 )
		{
			fclose( file );
			return ContentLauncher::FileIoError;
		}
		const long fileSize = ftell( file );
		if( fileSize <= 0 )
		{
			fclose( file );
			return ContentLauncher::FileIoError;
		}
		if( (unsigned long)fileSize > MaxExecutableBytes )
		{
			fclose( file );
			return ContentLauncher::ExecutableTooLarge;
		}
		rewind( file );

		const u32 executableSize = (u32)fileSize;
		const size_t bytesRead = fread( ExecutableAddress, 1, executableSize, file );
		const bool readFailed = bytesRead != executableSize || ferror( file );
		fclose( file );
		if( readFailed )
			return ContentLauncher::FileIoError;

		const bool elf = IsElf( ExecutableAddress, executableSize );
		if( !elf && !IsDol( ExecutableAddress, executableSize ) )
			return ContentLauncher::InvalidExecutable;

		memset( ArgumentsAddress, 0, sizeof( struct __argv ) );
		DCFlushRange( ArgumentsAddress, sizeof( struct __argv ) );
		if( !IsDollZ( ExecutableAddress, executableSize )
			&& !IsSpecialElf( ExecutableAddress, executableSize ) )
		{
			const s32 argvResult = PrepareArguments( executablePath, arguments );
			if( argvResult < 0 )
				return argvResult;
		}

		DCFlushRange( ExecutableAddress, executableSize );
		ICInvalidateRange( ExecutableAddress, executableSize );
		memcpy( BooterAddress, AppBooter, sizeof( AppBooter ) );
		DCFlushRange( BooterAddress, sizeof( AppBooter ) );
		ICInvalidateRange( BooterAddress, sizeof( AppBooter ) );

		// This is the irreversible handoff.  Every possible validation and file
		// error has returned above, so the caller no longer needs a live SD or
		// ISFS session. IOS58 is the standard homebrew runtime IOS.
		QuiesceInputForLaunch();
		fatUnmount( "sd" );
		ISFS_Deinitialize();
		if( IOS_GetVersion() != 58 )
			IOS_ReloadIOS( 58 );

		SYS_ResetSystem( SYS_SHUTDOWN, 0, 0 );
		const u32 level = IRQ_Disable();
		__exception_closeall();
		( (EntryPoint)BooterAddress )();
		// The app-booter is not allowed to return after libogc shutdown.  There
		// is no valid UI/audio/thread state to resume, so reboot instead of
		// drawing from torn-down subsystems.
		IRQ_Restore( level );
		SYS_ResetSystem( SYS_RESTART, 0, 0 );
		for( ;; )
			;
	}
